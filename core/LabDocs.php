<?php
// Selfcare original code. Printable documents of the clinic laboratory suite, built as models for Documents::pdf(), and a small XLSX writer.
// Every document carries a number and, from the second print on, a DUPLICATE / REPRINT mark. Each print is written to the record history.
declare(strict_types=1);

namespace Selfcare;

final class LabDocs
{
    public function __construct(private Lab $L) {}

    private function org(): array
    {
        $o = Documents::org(app(), $this->L->t);
        $n = trim((string) $this->L->setting('report_title'));
        if ($n !== '') {
            $o['name'] = $n;
        }
        return $o;
    }

    private function base(string $title, string $no, array $blocks, string $mark = ''): array
    {
        return ['title' => $title, 'no' => $no, 'date' => date('d M Y'), 'org' => $this->org(), 'blocks' => $blocks, 'status' => $mark, 'printed_by' => trim($this->L->p->user['first_name'] . ' ' . ($this->L->p->user['last_name'] ?? '')), 'printed_at' => date('d M Y, H:i'), 'generator' => (string) $this->L->setting('footer', 'Generated by Self Care')];
    }

    /** Marks a print. Returns the mark text for the document header: empty on the first print. */
    public function mark(string $entity, int $id, int $branch): string
    {
        $n = (int) $this->L->db->val("SELECT COUNT(*) FROM sc_record_history WHERE tenant_id = ? AND entity = ? AND entity_id = ? AND action = 'printed'", [$this->L->t, $entity, $id]);
        $this->L->log($entity, $id, 'printed', null, ['copy' => $n + 1], null, $branch);
        return $n > 0 ? 'DUPLICATE / REPRINT ' . ($n + 1) : '';
    }

    private function patientKv(array $pt, array $extra = []): array
    {
        return ['kv', 'title' => 'Patient', 'items' => array_merge([['Name', $pt['name']], ['MR number', $pt['mr']], ['Age / sex', trim(Lab::ageText($pt) . ' / ' . Lab::sexName($pt['gender']), ' /')], ['Phone', (string) $pt['phone']], ['Guardian', (string) $pt['guardian']], ['CNIC', (string) $pt['cnic']]], $extra)];
    }

    public function slip(array $o, string $mark): array
    {
        Currency::$context = $this->L->money($o)['cur'];
        $pt = $this->L->patient((int) $o['patient_id']);
        $rows = [];
        foreach ($this->L->items((int) $o['id']) as $i) {
            if ($i['status'] !== 'cancelled') {
                $rows[] = [(string) $i['test_name'], (string) $i['specimen'], money((float) $i['net'])];
            }
        }
        $ref = $o['referrer_id'] ? (string) $this->L->db->val('SELECT name FROM sc_referrers WHERE id = ?', [(int) $o['referrer_id']]) : 'Walk in';
        $b = [$this->patientKv($pt, [['Branch', $this->L->branchName((int) $o['branch_id'])], ['Referred by', $ref], ['Collection', $o['collection'] === 'home' ? 'Home collection' : 'At the lab'], ['Booked', dt((string) $o['order_date'], 'd M Y, H:i')]]), ['table', 'title' => 'Tests booked', 'cols' => [['Test', 300], ['Specimen', 110], ['Amount', 90, 'R']], 'rows' => $rows]];
        $m = $this->L->money($o);
        $b[] = ['totals', 'rows' => [['Subtotal', money((float) $o['subtotal'] + (float) $o['home_charge'])], ['Discount', money((float) $o['discount'])], ['Total', money($m['total'])], ['Paid', money($m['paid'])], ['Balance due', money($m['balance']), true]]];
        $b[] = ['note', 'body' => 'Please bring this slip to collect your report. Reports are given only after approval by the pathologist.'];
        return $this->base('Booking slip', (string) $o['order_no'], $b, $mark);
    }

    public function receipt(array $o, ?array $pay, string $mark): array
    {
        Currency::$context = $this->L->money($o)['cur'];
        $pt = $this->L->patient((int) $o['patient_id']);
        $m = $this->L->money($o);
        $b = [$this->patientKv($pt), ['kv', 'title' => 'Payment', 'items' => [['Receipt no', (string) ($pay['receipt_no'] ?? '')], ['Order', (string) $o['order_no']], ['Invoice', (string) $o['invoice_no']], ['Method', (string) ($pay['method'] ?? '')], ['Reference', (string) ($pay['reference'] ?? '')], ['Received on', $pay ? dt((string) $pay['paid_at'], 'd M Y, H:i') : '']]],
            ['totals', 'rows' => [['Amount received', money((float) ($pay['amount'] ?? 0)), true], ['Paid so far', money($m['paid'])], ['Balance due', money($m['balance'])]]]];
        return $this->base('Payment receipt', (string) ($pay['receipt_no'] ?? $o['order_no']), $b, $mark);
    }

    /** The patient report: every approved test of the order, with ranges and flags, and the signatory. */
    public function report(array $o, array $items, string $mark): array
    {
        $pt = $this->L->patient((int) $o['patient_id']);
        $b = [$this->patientKv($pt, [['Order', (string) $o['order_no']], ['Collected', $this->L->db->val("SELECT DATE_FORMAT(MIN(collected_at), '%d %b %Y %H:%i') FROM sc_lab_samples WHERE order_id = ?", [(int) $o['id']]) ?: ''], ['Branch', $this->L->branchName((int) $o['branch_id'])]])];
        $sign = [];
        foreach ($items as $it) {
            $rows = [];
            foreach ($this->L->results((int) $it['id']) as $r) {
                $rows[] = [(string) $r['param_name'], (string) $r['value'], $r['flag'] === 'H' ? 'High' : ($r['flag'] === 'L' ? 'Low' : ''), (string) $r['unit'], (string) $r['ref_text']];
            }
            $b[] = ['table', 'title' => $it['test_name'] . ' · ' . ($it['dept_name'] ?: '') . ($it['version'] > 1 ? ' · Amended, version ' . $it['version'] : '') . ' · Report ' . $it['report_no'], 'cols' => [['Test', 190], ['Result', 80, 'R'], ['Flag', 40], ['Unit', 60], ['Reference range', 140]], 'rows' => $rows];
            if ($it['signatory_id']) {
                $s = $this->L->db->one('SELECT name, title, reg_no FROM sc_lab_signatories WHERE id = ?', [(int) $it['signatory_id']]);
                $sign[(string) $s['name']] = $s['name'] . ' · ' . $s['title'] . ($s['reg_no'] ? ' · ' . $s['reg_no'] : '');
            }
        }
        $b[] = ['note', 'body' => 'High and Low flags compare the result with the reference range for the patient age and sex. This report is valid only when approved and signed. Results should be read with the clinical picture.'];
        $m = $this->base('Laboratory report', (string) $o['order_no'], $b, $mark);
        $m['sign'] = array_values($sign) ?: ['Authorised signatory'];
        return $m;
    }

    public function commissionStatement(array $ref, string $from, string $to, string $mark = ''): array
    {
        $T = $this->L->commissionTotals((int) $ref['id'], $from, $to);
        $rows = [];
        foreach ($this->L->db->all("SELECT c.*, o.order_no, o.order_date FROM sc_commissions c JOIN sc_lab_orders o ON o.id = c.order_id WHERE c.tenant_id = ? AND c.referrer_id = ? AND DATE(c.created_at) BETWEEN ? AND ? AND " . $this->L->scope('c.branch_id') . ' ORDER BY c.id', [$this->L->t, (int) $ref['id'], $from, $to]) as $r) {
            $rows[] = [dt((string) $r['created_at'], 'd M Y'), (string) $r['order_no'], ucfirst((string) $r['kind']), (string) ($r['note'] ?: $r['rule']), money((float) $r['amount'])];
        }
        $paid = [];
        foreach ($this->L->db->all("SELECT * FROM sc_ledger WHERE tenant_id = ? AND source = 'commission' AND referrer_id = ? AND deleted_at IS NULL AND status = 'paid' AND entry_date BETWEEN ? AND ?", [$this->L->t, (int) $ref['id'], $from, $to]) as $r) {
            $paid[] = [dt((string) $r['entry_date'], 'd M Y'), (string) $r['code'], (string) $r['method'], (string) $r['reference'], money((float) $r['amount'])];
        }
        $b = [['kv', 'title' => ucfirst((string) $ref['kind']) . ' commission statement', 'items' => [['Name', (string) $ref['name']], ['Period', dt($from) . ' to ' . dt($to)], ['Patients referred', (string) $T['patients']], ['Orders', (string) $T['orders']], ['Tests referred', (string) $T['tests']]]],
            ['table', 'title' => 'Earned, with adjustments for refunds, discounts and cancellations', 'cols' => [['Date', 70], ['Order', 120], ['Type', 70], ['Basis', 200], ['Amount', 70, 'R']], 'rows' => $rows],
            ['table', 'title' => 'Payments made', 'cols' => [['Date', 70], ['No', 80], ['Method', 90], ['Reference', 150], ['Amount', 70, 'R']], 'rows' => $paid],
            ['totals', 'rows' => [['Earned', money((float) $T['earned'])], ['Paid', money((float) $T['paid'])], ['Outstanding', money((float) $T['outstanding']), true]]]];
        return $this->base('Commission statement', strtoupper(substr((string) $ref['kind'], 0, 3)) . '-' . $ref['id'] . '-' . str_replace('-', '', $to), $b, $mark);
    }

    public function salarySlip(array $s, array $u, array $adj, string $mark = ''): array
    {
        Currency::$context = (string) ($s['currency'] ?: $this->L->branchCurrency((int) $s['branch_id']));
        $rows = [['Basic salary', money((float) $s['base'])]];
        foreach ($adj as $a) {
            $rows[] = [ucfirst((string) $a['kind']) . ($a['reason'] ? ': ' . $a['reason'] : ''), ($a['kind'] === 'bonus' ? '+' : '-') . money((float) $a['amount'])];
        }
        $b = [['kv', 'title' => 'Employee', 'items' => [['Name', trim($u['first_name'] . ' ' . ($u['last_name'] ?? ''))], ['Staff no', (string) ($u['staff_no'] ?? '')], ['Designation', (string) ($u['designation'] ?? '')], ['Period', (string) $s['period']], ['Branch', $this->L->branchName((int) $s['branch_id'])], ['Status', ucfirst((string) $s['status'])]]],
            ['table', 'title' => 'Earnings and deductions', 'cols' => [['Item', 380], ['Amount', 120, 'R']], 'rows' => $rows],
            ['totals', 'rows' => [['Net salary', money((float) $s['net'])], ['Paid', money((float) $s['paid'])], ['Still due', money((float) $s['net'] - (float) $s['paid']), true]]]];
        return $this->base('Salary slip', 'SAL-' . $s['id'] . '-' . str_replace('-', '', (string) $s['period']), $b, $mark);
    }

    /** Plain table document for lists and reports. @param list<array{0:string,1:float}> $cols @param list<list<string>> $rows */
    public function table(string $title, string $no, array $kv, array $cols, array $rows, array $totals = [], string $mark = '', bool $landscape = false): array
    {
        $b = [];
        if ($kv) {
            $b[] = ['kv', 'title' => 'Details', 'items' => $kv];
        }
        $b[] = ['table', 'title' => $title, 'cols' => $cols, 'rows' => $rows];
        if ($totals) {
            $b[] = ['totals', 'rows' => $totals];
        }
        $m = $this->base($title, $no, $b, $mark);
        $m['landscape'] = $landscape;
        return $m;
    }

    public function sampleLabel(array $s, array $o): array
    {
        $pt = $this->L->patient((int) $o['patient_id']);
        return $this->base('Sample label', (string) $s['barcode'], [['kv', 'title' => 'Sample', 'items' => [['Patient', $pt['name']], ['MR', $pt['mr']], ['Specimen', (string) $s['specimen']], ['Order', (string) $o['order_no']], ['Branch', $this->L->branchName((int) $s['branch_id'])]]]]);
    }

    // ------------------------------------------------------------------ XLSX

    /** Builds an .xlsx file. $sheets: name => list of rows (first row is the header). Returns bytes. @param array<string,list<list<scalar>>> $sheets */
    public static function xlsx(array $sheets): string
    {
        $tmp = tempnam(sys_get_temp_dir(), 'xl');
        $z = new \ZipArchive();
        $z->open($tmp, \ZipArchive::OVERWRITE);
        $e = static fn ($v): string => htmlspecialchars((string) $v, ENT_XML1 | ENT_QUOTES, 'UTF-8');
        $col = static function (int $i): string {
            $s = '';
            for ($i++; $i > 0; $i = intdiv($i - 1, 26)) {
                $s = chr(65 + ($i - 1) % 26) . $s;
            }
            return $s;
        };
        $ct = '<?xml version="1.0" encoding="UTF-8" standalone="yes"?><Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types"><Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/><Default Extension="xml" ContentType="application/xml"/><Override PartName="/xl/workbook.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.sheet.main+xml"/><Override PartName="/xl/styles.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.styles+xml"/>';
        $wb = '<?xml version="1.0" encoding="UTF-8" standalone="yes"?><workbook xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main" xmlns:r="http://schemas.openxmlformats.org/officeDocument/2006/relationships"><sheets>';
        $wr = '<?xml version="1.0" encoding="UTF-8" standalone="yes"?><Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">';
        $n = 0;
        foreach ($sheets as $name => $rows) {
            $n++;
            $ct .= '<Override PartName="/xl/worksheets/sheet' . $n . '.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.worksheet+xml"/>';
            $wb .= '<sheet name="' . $e(mb_substr(preg_replace('/[\\\\\/?*\[\]:]/', ' ', (string) $name), 0, 31)) . '" sheetId="' . $n . '" r:id="rId' . $n . '"/>';
            $wr .= '<Relationship Id="rId' . $n . '" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/worksheet" Target="worksheets/sheet' . $n . '.xml"/>';
            $x = '<?xml version="1.0" encoding="UTF-8" standalone="yes"?><worksheet xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main"><sheetData>';
            foreach ($rows as $ri => $row) {
                $x .= '<row r="' . ($ri + 1) . '">';
                foreach (array_values($row) as $ci => $v) {
                    $ref = $col($ci) . ($ri + 1);
                    if (is_int($v) || is_float($v) || (is_string($v) && $v !== '' && is_numeric($v) && !preg_match('/^0\d/', $v) && strlen($v) < 15)) {
                        $x .= '<c r="' . $ref . '"' . ($ri === 0 ? ' s="1"' : '') . '><v>' . (0 + $v) . '</v></c>';
                    } else {
                        $x .= '<c r="' . $ref . '" t="inlineStr"' . ($ri === 0 ? ' s="1"' : '') . '><is><t xml:space="preserve">' . $e($v) . '</t></is></c>';
                    }
                }
                $x .= '</row>';
            }
            $z->addFromString('xl/worksheets/sheet' . $n . '.xml', $x . '</sheetData></worksheet>');
        }
        $z->addFromString('[Content_Types].xml', $ct . '</Types>');
        $z->addFromString('_rels/.rels', '<?xml version="1.0" encoding="UTF-8" standalone="yes"?><Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships"><Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/officeDocument" Target="xl/workbook.xml"/></Relationships>');
        $z->addFromString('xl/workbook.xml', $wb . '</sheets></workbook>');
        $z->addFromString('xl/_rels/workbook.xml.rels', $wr . '<Relationship Id="rIdS" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/styles" Target="styles.xml"/></Relationships>');
        $z->addFromString('xl/styles.xml', '<?xml version="1.0" encoding="UTF-8" standalone="yes"?><styleSheet xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main"><fonts count="2"><font><sz val="11"/><name val="Calibri"/></font><font><b/><sz val="11"/><name val="Calibri"/></font></fonts><fills count="2"><fill><patternFill patternType="none"/></fill><fill><patternFill patternType="gray125"/></fill></fills><borders count="1"><border><left/><right/><top/><bottom/><diagonal/></border></borders><cellStyleXfs count="1"><xf numFmtId="0" fontId="0" fillId="0" borderId="0"/></cellStyleXfs><cellXfs count="2"><xf numFmtId="0" fontId="0" fillId="0" borderId="0" xfId="0"/><xf numFmtId="0" fontId="1" fillId="0" borderId="0" xfId="0" applyFont="1"/></cellXfs></styleSheet>');
        $z->close();
        $bytes = (string) file_get_contents($tmp);
        @unlink($tmp);
        return $bytes;
    }
}
