<?php
// Selfcare original code. Writes the table of every invoice, form and report for each vendor type.
//   php database/phase1/gen-doc-index.php [samples_dir] > docs/documents-and-reports.md
// Reads the same config files the app uses, so the table can never disagree with the code.
declare(strict_types=1);

foreach (['Env', 'Database', 'VendorTypes', 'Billing', 'Reports'] as $f) {
    require_once dirname(__DIR__, 2) . '/core/' . $f . '.php';
}
$samples = rtrim($argv[1] ?? '/workspace/selfcare/redesign/pdf-samples', '/');
$docs = require dirname(__DIR__, 2) . '/core/config/documents.php';
$vt = require dirname(__DIR__, 2) . '/core/config/vendor_types.php';
// Billing only needs the config for catalog(); no database is touched here.
$ref = new ReflectionClass(Selfcare\Billing::class);
$bill = $ref->newInstanceWithoutConstructor();
$prop = $ref->getProperty('cfg');
$prop->setAccessible(true);
$prop->setValue($bill, $docs);

$sample = static function (string $type, string $kind, string $key, bool $blank = false) use ($samples): string {
    $dir = $kind === 'invoice' ? 'invoices' : ($kind === 'form' ? 'forms' : 'reports');
    $f = "$samples/$type/$dir/" . ($blank ? 'blank-' : '') . "$key.pdf";
    return is_file($f) ? '`' . $f . '`' : 'not generated (plan or data)';
};
$invTables = static function (array $c): string {
    $t = ['sc_invoices', 'sc_invoice_items', 'sc_invoice_payments', 'sc_number_sequences', 'settings', 'tenants', 'front_settings'];
    if (($c['party'] ?? '') === 'Patient') {
        $t[] = 'patients';
        $t[] = 'doctors';
        $t[] = 'users';
    }
    if (!empty($c['stock'])) {
        $t[] = 'sc_stock_items';
    }
    return implode(', ', array_unique($t));
};
$out = "# Invoices, forms and reports by vendor type\n\nGenerated by `database/phase1/gen-doc-index.php` from `core/config/documents.php`, `core/config/vendor_types.php` and `core/Reports.php`.\n\n";
$out .= "How to read the tables:\n\n";
$out .= "- **Invoices** are saved in `sc_invoices` (+ items and payments). Screen: `GET /portal/billing/{id}` (HTML sheet from `Documents::html()`, rendered in `templates/dash/layout.php` + `templates/dash/raw.php`). PDF: `GET /portal/billing/{id}/pdf` (`Documents::pdf()` in `core/Documents.php`, model built by `Billing::invoiceModel()`). Create: `GET /portal/billing/new/{type}` then `POST /portal/billing/save`. Routes live in `core/routes/documents.php`.\n";
$out .= "- **Forms** (hand-filled documents digitised) are saved in `sc_documents` (`data` JSON). Fill: `GET /portal/documents/{type}/new` then `POST /portal/documents/{type}/save`. Screen: `GET /portal/documents/{type}/{id}`. PDF: `GET /portal/documents/{type}/{id}/pdf`. Blank to write by hand: `GET /portal/documents/{type}/blank`. Model: `Billing::formModel()`.\n";
$out .= "- **Reports** are computed by `Reports::run()` and shown at `GET /portal/reports/{key}?from=&to=&q=`; `&format=pdf` downloads the PDF (`Reports::model()` + `Documents::pdf()`).\n";
$out .= "- Every route needs the matching permission through the existing role table (`manage_invoices`, `manage_reports`, `manage_prescriptions`, `manage_patients`, `manage_medicines`, `manage_blood_bank`) and the plan module (`billing`, `documents`, `reports`, `ipd`, `procurement`, `insurance`).\n";
$out .= "- Every document reads `tenants`, `front_settings` and `settings` for its header (name, address, phone, licence number, logo, currency, invoice prefix) and `sc_number_sequences` for its number.\n\n";
$typeNames = [];
foreach ($vt['types'] as $slug => $t) {
    $typeNames[$slug] = [$t[0], $t[2]];
}
foreach ($typeNames as $slug => [$name, $family]) {
    $cat = $bill->catalog($slug, $family);
    $out .= "## $name (`$slug`, family `$family`)\n\n| Kind | Document | Route | Template / model | Tables read | Sample PDF |\n| --- | --- | --- | --- | --- | --- |\n";
    foreach ($cat['invoices'] as $k => $c) {
        $out .= "| Invoice | {$c['label']} (`$k`, prefix `{$c['prefix']}`) | `/portal/billing/new/$k`, `/portal/billing/{id}/pdf` | `Documents::html/pdf`, `Billing::invoiceModel` | " . $invTables($c) . ' | ' . $sample($slug, 'invoice', $k) . " |\n";
    }
    foreach ($cat['forms'] as $k => $c) {
        $out .= "| Form | {$c['label']} (`$k`) | `/portal/documents/$k/new`, `/portal/documents/$k/{id}/pdf`, `/portal/documents/$k/blank` | `Documents::html/pdf`, `Billing::formModel` | sc_documents, sc_number_sequences, settings, tenants, front_settings | " . $sample($slug, 'form', $k) . '; blank: ' . $sample($slug, 'form', $k, true) . " |\n";
    }
    foreach (Selfcare\Reports::forFamily($family, $slug) as $k) {
        $m = Selfcare\Reports::META[$k];
        $out .= "| Report | {$m[0]} (`$k`) | `/portal/reports/$k`, `/portal/reports/$k?format=pdf` | `Reports::run/model`, `Documents::pdf` | {$m[2]} | " . $sample($slug, 'report', $k) . " |\n";
    }
    foreach (array_keys($cat['forms']) as $k) {
        if (empty($cat['forms'][$k]['register'])) {
            continue;
        }
        $out .= "| Report | Register of {$cat['forms'][$k]['label']} (`reg-$k`) | `/portal/reports/reg-$k`, `/portal/reports/reg-$k?format=pdf` | `Reports::run/model` | sc_documents | " . $sample($slug, 'report', 'reg-' . $k) . " |\n";
    }
    $out .= "\n";
}
$out .= "## Super admin (platform)\n\n| Kind | Document | Route | Template / model | Tables read | Sample PDF |\n| --- | --- | --- | --- | --- | --- |\n";
foreach (['subscription_invoice', 'subscription_receipt', 'platform_credit_note'] as $k) {
    $c = $docs['invoices'][$k];
    $out .= "| Invoice | {$c['label']} (`$k`) | `/admin/billing/new`, `/admin/billing/{id}`, `/admin/billing/{id}/pdf` | `Documents::html/pdf`, `Billing::invoiceModel` | sc_invoices (issuer = platform), sc_invoice_items, sc_invoice_payments, sc_number_sequences (tenant `_platform`), sc_plans, tenants, front_settings | " . $sample('super-admin', 'invoice', $k) . " |\n";
}
foreach (Selfcare\Reports::platform() as $k) {
    $m = Selfcare\Reports::META[$k];
    $out .= "| Report | {$m[0]} (`$k`) | `/admin/reports/$k`, `/admin/reports/$k?format=pdf` | `Reports::run/model`, `Documents::pdf` | {$m[2]} | " . $sample('super-admin', 'report', $k) . " |\n";
}
echo $out;
